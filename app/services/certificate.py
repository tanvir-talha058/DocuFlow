"""Generate a one-page "Certificate of Completion" PDF summarizing a fully
approved chain: document, every approver, their decision, and when.
Attached to the chain once the last step is approved, so the sender has a
system-generated record to download alongside the original document."""

from pathlib import Path

import fitz  # PyMuPDF

from app.config import settings

_PAGE_WIDTH, _PAGE_HEIGHT = 595, 842  # A4 @ 72dpi
_MARGIN = 56
_INK = (0.09, 0.10, 0.17)
_INK_FAINT = (0.45, 0.46, 0.53)
_BRAND = (0.169, 0.227, 0.4)  # matches --ink-blue


def generate_certificate(*, chain, document, steps_with_approvers: list[tuple]) -> str:
    """steps_with_approvers: [(ApprovalStep, approver_record), ...] in step order.
    Returns the path the certificate PDF was written to."""
    doc = fitz.open()
    page = doc.new_page(width=_PAGE_WIDTH, height=_PAGE_HEIGHT)
    x = _MARGIN
    y = _MARGIN

    page.insert_text((x, y), "DocuFlow", fontsize=13, fontname="helv", color=_BRAND)
    y += 34
    page.insert_text((x, y), "Certificate of Completion", fontsize=20, fontname="helv", color=_INK)
    y += 22
    page.draw_line((x, y), (_PAGE_WIDTH - _MARGIN, y), color=(0.86, 0.87, 0.9), width=1)
    y += 30

    def label_value(label: str, value: str, size: int = 10.5) -> None:
        nonlocal y
        page.insert_text((x, y), label, fontsize=8.5, fontname="helv", color=_INK_FAINT)
        page.insert_text((x, y + 15), value, fontsize=size, fontname="helv", color=_INK)
        y += 40

    label_value("DOCUMENT", chain.title or document.original_filename)
    if chain.title:
        label_value("FILE NAME", document.original_filename, size=9.5)
    label_value("CHAIN ID", chain.id, size=9)
    label_value(
        "COMPLETED",
        chain.completed_at.strftime("%Y-%m-%d %H:%M UTC") if chain.completed_at else "",
    )

    y += 6
    page.insert_text((x, y), "Approval record", fontsize=12, fontname="helv", color=_INK)
    y += 16
    page.draw_line((x, y), (_PAGE_WIDTH - _MARGIN, y), color=(0.86, 0.87, 0.9), width=1)
    y += 24

    for step, approver in steps_with_approvers:
        if y > _PAGE_HEIGHT - 140:
            page = doc.new_page(width=_PAGE_WIDTH, height=_PAGE_HEIGHT)
            y = _MARGIN

        badge = f"{step.step_order}"
        page.draw_circle((x + 8, y + 2), 9, color=_BRAND, fill=_BRAND)
        page.insert_text((x + 8 - (3.2 if len(badge) == 1 else 5.5), y + 5), badge, fontsize=9, fontname="helv", color=(1, 1, 1))

        tx = x + 28
        name = approver.display_name if approver else "Unknown"
        email = approver.email if approver else ""
        kind = " (external signer)" if step.approver_type == "CUSTOMER" else ""
        page.insert_text((tx, y), f"{name}{kind}", fontsize=11, fontname="helv", color=_INK)
        page.insert_text((tx, y + 14), email, fontsize=9, fontname="helv", color=_INK_FAINT)

        status_label = "Approved" if step.status == "APPROVED" else step.status.replace("_", " ").title()
        when = step.approved_at or step.decided_at
        when_label = when.strftime("%Y-%m-%d %H:%M UTC") if when else ""
        status_color = (0.09, 0.45, 0.27) if step.status == "APPROVED" else _INK_FAINT
        page.insert_text((_PAGE_WIDTH - _MARGIN - 150, y), status_label, fontsize=10, fontname="helv", color=status_color)
        page.insert_text((_PAGE_WIDTH - _MARGIN - 150, y + 14), when_label, fontsize=8.5, fontname="helv", color=_INK_FAINT)

        y += 38

    y = max(y + 20, _PAGE_HEIGHT - 110)
    page.draw_line((x, y), (_PAGE_WIDTH - _MARGIN, y), color=(0.86, 0.87, 0.9), width=1)
    y += 20
    page.insert_textbox(
        fitz.Rect(x, y, _PAGE_WIDTH - _MARGIN, y + 60),
        "This certificate was system-generated by DocuFlow and confirms that every "
        "approver listed above reviewed and approved this document, in the order shown.",
        fontsize=8.5,
        fontname="helv",
        color=_INK_FAINT,
    )

    output_path = str(Path(settings.upload_dir) / f"{chain.id}_certificate.pdf")
    doc.save(output_path)
    doc.close()
    return output_path
